namespace CapitaModern.Core.Economy;

/// <summary>В чём страна держит запасы.</summary>
/// <remarks>Пока наполняется только <see cref="ForeignCurrency"/>: под остальное нет
/// рынков. Форма заложена сразу, чтобы потом не переписывать всё, что резервов
/// касается.</remarks>
public enum ReserveKind
{
    /// <summary>Чужая валюта. Лежит в банках эмитента, поэтому он её и морозит.</summary>
    ForeignCurrency,

    /// <summary>Чужие облигации: приносят купон, хранятся у эмитента.</summary>
    Bond,

    /// <summary>Чужие акции: приносят дивиденд, цена ходит.</summary>
    Equity,

    /// <summary>Золото и прочие металлы. Хранить можно и дома, и в чужом хранилище —
    /// от этого и зависит, отнимут или нет.</summary>
    Metal,

    /// <summary>Криптовалюта. Хранится у себя, но цена ходит сильнее всего.</summary>
    Crypto,
}
