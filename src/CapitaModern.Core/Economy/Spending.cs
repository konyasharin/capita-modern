namespace CapitaModern.Core.Economy;

/// <summary>Сколько чего купят люди при таком доходе и таких ценах.</summary>
/// <remarks>
/// Прежде спрос был нормой: столько-то еды на миллион человек, и всё. Норма чуть менялась
/// с достатком, но по сути стояла на месте — дай людям вдвое больше денег, и они купят
/// столько же. Оттого и не работал кругооборот: деньги приходили к людям и оседали, выпуск
/// сверх нормы никому не был нужен, а цена на него падала.
///
/// Здесь иначе: сперва люди покупают прожиточный минимум, а что осталось от дохода —
/// делят между товарами долями. Это система расходов Стоуна и Гири, и из неё сами собой
/// выходят три вещи, которые прежде задавались руками:
///
///   • закон Энгеля — у бедного весь доход уходит на минимум, и доля еды велика; у
///     богатого минимум занимает малую часть, и доля еды падает;
///   • отзывчивость на доход — больше денег значит больше покупок;
///   • отзывчивость на цену — дорогой товар съедает больше дохода, и на прочее остаётся
///     меньше.
/// </remarks>
public static class Spending
{
    /// <summary>В сотых: сколько дохода уходит на потребление, а не в сбережения.</summary>
    /// <remarks>
    /// В жизни у домохозяйств это восемь-девять десятых, но там остаток возвращается в
    /// хозяйство займами и вложениями почти целиком, а здесь он оседает у людей мёртвым
    /// грузом: банк раздаёт лишь долю вкладов, и круг не замыкается.
    ///
    /// Девять десятых оставляли семнадцать процентов выпуска без покупателя — товар шёл на
    /// склад, правило загрузки видело избыток и глушило заводы. Отсюда и потолок роста:
    /// сколько ни строй, выпускать сверх спроса некуда.
    /// </remarks>
    public const int Spends = 97;

    /// <summary>Сколько товара купят: минимум плюс доля свободных денег.</summary>
    /// <param name="income">Дневной доход всех людей страны.</param>
    /// <param name="floor">Во что обходится прожиточный минимум целиком.</param>
    /// <param name="price">Цена товара.</param>
    /// <param name="least">Сколько его нужно по минимуму.</param>
    /// <param name="share">Какая доля свободных денег уходит на него, в сотых.</param>
    public static GoodAmount Wanted(
        Money income, Money floor, Money price, GoodAmount least, int share)
    {
        if (price.Raw <= 0) return least;

        var purse = new Money(income.Raw * Spends / 100);

        // На минимум денег не хватает — берут сколько смогут, и это уже голод.
        if (purse <= floor)
        {
            return floor.Raw <= 0
                ? default
                : new GoodAmount((long)((Int128)least.Raw * purse.Raw / floor.Raw));
        }

        var spare = purse - floor;
        var onThis = new Money(spare.Raw * share / 100);

        return least + new GoodAmount((long)((Int128)onThis.Raw * GoodAmount.Scale / price.Raw));
    }
}
