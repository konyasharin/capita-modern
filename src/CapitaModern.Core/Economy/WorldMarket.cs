namespace CapitaModern.Core.Economy;

/// <summary>Мировая цена товара: та, по которой сошлись сделки за прошедший тик.</summary>
/// <remarks>
/// Раньше здесь был общий котёл: все заявки сваливались в одну кучу, товар делился по
/// доле, цена была одна на всех. Считалось быстро и неверно — в котле нет пути от
/// продавца к покупателю, поэтому нельзя ни посчитать расстояние, ни перекрыть дорогу,
/// ни отказаться покупать у конкретной страны. Сводит теперь <see cref="Exchange"/>, а
/// здесь остался только сам ценник: средняя цена сделок как показатель мира.
/// </remarks>
public sealed class WorldMarket
{
    /// <summary>Чья валюта приходит за экспорт. Ничья: мировая единица — мера, а не
    /// валюта страны. Какая валюта станет резервной, пусть решится само.</summary>
    public const byte WorldIssuer = 0;

    public Prices Prices { get; }

    public WorldMarket(Prices prices)
    {
        Prices = prices;
    }
}
