namespace CapitaModern.Core.Economy;

/// <summary>Где занято. Разделение нужно ради дефолта: отказаться можно по внешнему
/// долгу, а по внутреннему это уже не дефолт, а инфляция или заморозка вкладов.</summary>
public enum LoanSource
{
    /// <summary>У чужой страны. Пока единственный работающий.</summary>
    Foreign,

    /// <summary>У своих банков и населения. Ждёт зарплат и налогов: сейчас денег
    /// внутри страны попросту не у кого взять.</summary>
    Domestic,

    /// <summary>МВФ и подобные. Дают под условия, а не под ставку — отдельная механика.</summary>
    Multilateral,
}
