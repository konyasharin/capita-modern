namespace CapitaModern.Core.Economy;

/// <summary>Как государство напечатало деньги.</summary>
/// <remarks>Считается это одинаково: деньги созданы, инфляция будет. Разница
/// политическая. «Центробанк напечатал триллион» и «банки купили гособлигации» — разные
/// заголовки, и стоить в доверии они должны по-разному.</remarks>
public enum EmissionKind
{
    /// <summary>Прямо и открыто.</summary>
    Open,

    /// <summary>Через банки: им дают деньги, они на них покупают гособлигации.</summary>
    ThroughBanks,

    /// <summary>Под купленную валюту. Это не дыра в бюджете, а обычная работа
    /// центробанка: за вывоз в страну приходит чужая валюта, и он меняет её на свои
    /// деньги.</summary>
    ForCurrency,
}
